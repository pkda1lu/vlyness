//! # vlyness-profile
//!
//! Модель Profile и валидатор когерентности (дизайн §1).
//!
//! Profile — центральный объект: единая легенда, из которой детерминированно
//! выводится всё наблюдаемое (DNS/SNI/cert, JA3, HTTP/2 SETTINGS, UA, форма трафика,
//! ASN, ECH). [`validate`] проверяет **инвариант когерентности**: все слои должны
//! описывать одно приложение, иначе ТСПУ ловит несогласованность (01 §4). Несовместимый
//! профиль отклоняется до старта, а не «работает криво».

#![forbid(unsafe_code)]

pub mod model;
pub mod validate;

pub use model::*;
pub use validate::{validate, CoherenceError};
