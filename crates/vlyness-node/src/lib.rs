//! # vlyness-node
//!
//! Движок релея, превращающий сессию VLYNESS в настоящий прокси:
//! - [`run_server_relay`] — серверная сторона: на каждый `Open` коннектится к реальной
//!   цели и пробрасывает байты (тело `SessionHandler` носителя);
//! - [`TunnelClient`] — клиентская сторона: держит один туннель и открывает в нём потоки
//!   к целям, подключая локальные сокеты.
//!
//! Оба используют одну актор-проводку (см. [`relay`]): один writer-таск мультиплексирует,
//! один reader-таск демультиплексирует, по два таска на поток. Всё в одном соединении
//! (признак №5). Дисциплина (`vlyness-discipline`) и профиль (`vlyness-profile`)
//! подключаются на уровне бинарников поверх этого движка.

#![forbid(unsafe_code)]

pub mod relay;
pub mod socks;

pub use relay::{run_server_relay, TunnelClient, TunnelStats};
pub use socks::socks5_accept;
