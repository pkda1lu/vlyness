//! Связь релея с нативным datagram-каналом носителя (форма RTC-медиа).
//!
//! Носитель (например, QUIC/WebTransport) умеет слать **ненадёжные датаграммы** рядом с
//! надёжным стримом сессии. Атомарные UDP-кадры (`MuxEvent::Datagram`) выгоднее гнать
//! именно так: тогда форма трафика становится datagram-доминантной, как у видеозвонка, а
//! не bulk-стримом. Шифрование — [`vlyness_core::datagram`] (по датаграмме на seal,
//! скользящее окно анти-реплея), ключи выведены из хеша хендшейка сессии.
//!
//! Этот тип — «труба» между релеем и носителем: релей не знает про QUIC, а носитель не
//! знает про mux. Носитель отдаёт две mpsc-очереди **зашифрованных** датаграмм (наружу и
//! внутрь), релей владеет [`DatagramSealer`]/[`DatagramOpener`] и переводит между ними и
//! событиями mux. TCP-поток и управляющие кадры продолжают идти по надёжному стриму.

use tokio::sync::mpsc;

pub use vlyness_core::datagram::{
    channel, DatagramOpener, DatagramSealer, Role, DGRAM_OVERHEAD,
};

/// Труба к нативному datagram-каналу носителя, передаётся релею.
pub struct DatagramLink {
    /// Зашифрованные датаграммы наружу (релей → носитель → сеть).
    pub outbound: mpsc::Sender<Vec<u8>>,
    /// Зашифрованные датаграммы внутрь (сеть → носитель → релей).
    pub inbound: mpsc::Receiver<Vec<u8>>,
    /// Запечатыватель исходящих (счётчик ведётся внутри).
    pub sealer: DatagramSealer,
    /// Распечатыватель входящих (окно анти-реплея внутри).
    pub opener: DatagramOpener,
    /// Максимум **plaintext** в одной датаграмме (MTU носителя минус оверхед обёртки).
    /// Кадр крупнее уходит по надёжному стриму — атомарность сохраняется.
    pub max_plaintext: usize,
}
