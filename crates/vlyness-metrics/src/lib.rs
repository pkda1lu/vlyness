//! # vlyness-metrics
//!
//! Harness измеримости: проверяет **работает ли маскировка** (док 04 §2), а не просто
//! декларирует её. ТСПУ отличает наш трафик, обучив классификатор на потоковых
//! признаках; мы аппроксимируем его силу расхождением распределений между наблюдаемым
//! трафиком и легендой.
//!
//! - [`flow`] — наблюдаемый поток (размеры/направления/тайминги) и его признаки;
//! - [`distance`] — KS и гистограммные расстояния (DoD дока 04 §3);
//! - [`legend`] — эталонное распределение легенды для сравнения.
//!
//! Крейт **чистый** (без async): наблюдения собираются снаружи (в тестах — через
//! инструментирующую обёртку потока), а здесь только анализ. Это честный измеритель,
//! а не «докажем, что всё хорошо»: он показывает и где shaping держится, и где ломается
//! (напр. bulk-трафик уводит размеры записей от легенды).

#![forbid(unsafe_code)]

pub mod distance;
pub mod flow;
pub mod legend;

pub use distance::{class_fractions, hist_l1, ks_two_sample};
pub use flow::{Dir, Flow, Obs};
pub use legend::{LegendModel, MEDIA_CLASS_EDGES};
